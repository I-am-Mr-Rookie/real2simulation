// Body shaped per evidence/S18/S18k-TRACE-CONTRACT.md, generated by the accepted simulator (synthetic inputs).
function makeBody(steps = 40) {
  const sim = projectileTrajectory({ initialPosition: [0, 1, 0], initialVelocity: [3, 4, 0], gravity: 9.81, dt: 0.02, steps, source: 'simulated', inputProvenance: 'synthetic' });
  return { kind: sim.kind, source: sim.source, inputProvenance: 'synthetic', dt_s: sim.dt_s, label: 'SIMULATED',
    samples: sim.samples.map(({ step, time_s, position_m }) => ({ step, time_s, position_m: [...position_m] })) };
}
const bytesOf = (b) => new TextEncoder().encode(JSON.stringify(b));
async function makeTrace(steps) { const bytes = bytesOf(makeBody(steps)); return traceFromBody(bytes, await sha256Hex(bytes)); }
const isInvalid = (e) => e instanceof ViewerError && e.code === 'INVALID_ARTIFACT';

function fakeDom() {
  const all = [];
  const node = (tag) => {
    const n = { tag, attrs: {}, children: [], parent: null, listeners: {}, textContent: '', value: '',
      setAttribute(k, v) { this.attrs[k] = String(v); if (k === 'value') this.value = String(v); },
      append(...c) { for (const x of c) { x.parent = this; this.children.push(x); } },
      remove() { if (this.parent) this.parent.children = this.parent.children.filter((x) => x !== this); this.parent = null; },
      addEventListener(e, f) { (this.listeners[e] ??= new Set()).add(f); },
      removeEventListener(e, f) { this.listeners[e]?.delete(f); },
      fire(e) { for (const f of this.listeners[e] ?? []) f(); } };
    all.push(n); return n;
  };
  const doc = { createElement: node, createElementNS: (_ns, t) => node(t) };
  const host = node('div'); host.ownerDocument = doc;
  return { host, find: (tag) => all.filter((n) => n.tag === tag && n.parent !== null || n.tag === tag && n === host) };
}
const fakeRaf = () => { const q = new Map(); let id = 0; return { raf: (f) => (q.set(++id, f), id), caf: (i) => q.delete(i), run(ms) { const fs = [...q.values()]; q.clear(); fs.forEach((f) => f(ms)); }, size: () => q.size }; };

test('valid simulator-produced body verifies by byte hash and is frozen', async () => {
  const t = await makeTrace();
  assert.ok(Object.isFrozen(t.samples[3].position_m));
  assert.equal(t.source, 'simulated');
  assert.deepEqual(checkTrace(structuredClone(t)), t);
});

test('rejects byte tamper, wrong labels, non-finite, non-dense, oversize, extra fields', async () => {
  const body = makeBody(), bytes = bytesOf(body), sha = await sha256Hex(bytes);
  const tampered = bytes.slice(); tampered[tampered.length - 3] ^= 1;
  await assert.rejects(traceFromBody(tampered, sha), /sha256 mismatch/);
  await assert.rejects(traceFromBody(bytesOf({ ...body, sha256: sha }), await sha256Hex(bytesOf({ ...body, sha256: sha }))), isInvalid);
  await assert.rejects(traceFromBody(new Uint8Array(TRACE_LIMITS.maxBodyBytes + 1), sha), /body size/);
  const good = { ...body, sha256: sha };
  const at = (i, patch) => ({ ...good, samples: good.samples.map((s, k) => k === i ? { ...s, ...patch } : s) });
  const cases = [
    { ...good, source: 'measured' }, { ...good, label: 'Real' }, { ...good, inputProvenance: 'image-derived' },
    at(5, { position_m: [NaN, 0, 0] }), at(5, { time_s: 0 }), at(5, { step: 6 }), at(2, { velocity_m_s: [0, 0, 0] }),
    { ...good, samples: [good.samples[0]] }, { ...good, extra: 1 }, { ...good, sha256: 'ABC' }, { ...good, dt_s: 0 },
    { ...good, samples: Array.from({ length: TRACE_LIMITS.maxSamples + 1 }, (_, i) => ({ step: i, time_s: i * good.dt_s, position_m: [0, 0, 0] })) },
  ];
  for (const c of cases) assert.throws(() => checkTrace(c), isInvalid);
});

test('sampleTrace interpolates and clamps', async () => {
  const s = (await makeTrace()).samples;
  assert.deepEqual(sampleTrace(s, -1).position, s[0].position_m);
  assert.deepEqual(sampleTrace(s, 99).position, s.at(-1).position_m);
  const mid = sampleTrace(s, (s[3].time_s + s[4].time_s) / 2);
  assert.equal(mid.i, 3);
  assert.ok(Math.abs(mid.position[0] - (s[3].position_m[0] + s[4].position_m[0]) / 2) < 1e-12);
});

test('mystery mode is refused before touching host or trace', async () => {
  const { host } = fakeDom();
  await assert.rejects(mountTrajectoryReplay(host, null, { mode: 'mystery' }), (e) => e.code === 'UNAVAILABLE');
  assert.equal(host.children.length, 0);
});

test('mount shows SIMULATED banner; scrub and play move marker; dispose cleans up', async () => {
  const { host } = fakeDom(); const r = fakeRaf(); const ac = new AbortController();
  const trace = await makeTrace();
  const v = await mountTrajectoryReplay(host, trace, { signal: ac.signal, raf: r.raf, caf: r.caf });
  const root = host.children[0];
  const flat = (n) => [n, ...n.children.flatMap(flat)];
  const nodes = flat(root), by = (tag) => nodes.filter((n) => n.tag === tag);
  assert.equal(by('p')[0].textContent, SIMULATED_BANNER);
  const [btn] = by('button'), [range] = by('input'), marker = by('circle')[0];
  assert.equal(range.attrs.type, 'range');
  assert.ok(range.attrs['aria-label']);
  const x0 = marker.attrs.cx;
  range.value = String(trace.samples.at(-1).time_s); range.fire('input');
  assert.notEqual(marker.attrs.cx, x0);
  range.value = '0'; range.fire('input');
  btn.fire('click'); assert.equal(btn.attrs['aria-pressed'], 'true');
  r.run(1000); r.run(1100); assert.notEqual(marker.attrs.cx, x0);
  btn.fire('click'); assert.equal(btn.attrs['aria-pressed'], 'false'); assert.equal(r.size(), 0);
  btn.fire('click'); assert.equal(r.size(), 1);
  ac.abort();
  assert.equal(host.children.length, 0);
  assert.equal(r.size(), 0);
  assert.equal(btn.listeners.click.size, 0);
  assert.equal(range.listeners.input.size, 0);
  v.dispose(); // idempotent
});

