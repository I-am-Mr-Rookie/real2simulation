// Regenerate: node Build/web/src/pwa/build-sw.mjs  -> Build/web/public/pwa/sw.js
import { readFileSync, writeFileSync, mkdirSync } from 'node:fs';
import { fileURLToPath, pathToFileURL } from 'node:url';

const here = (p) => fileURLToPath(new URL(p, import.meta.url));
export function buildSw() {
  const policy = readFileSync(here('./cache-policy.mjs'), 'utf8').replace(/^export /gm, '');
  const glue = readFileSync(here('./sw-glue.js'), 'utf8');
  return '// GENERATED by src/pwa/build-sw.mjs from cache-policy.mjs + sw-glue.js. Do not edit.\n' + policy + glue;
}
if (process.argv[1] && import.meta.url === pathToFileURL(process.argv[1]).href) {
  mkdirSync(here('../../public/pwa/'), { recursive: true });
  writeFileSync(here('../../public/pwa/sw.js'), buildSw());
  console.log('wrote public/pwa/sw.js');
}
