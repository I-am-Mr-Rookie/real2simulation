"""N12: lab report (Markdown + HTML) from a SIMULATED lab run. Every number is copied from the run results."""
from __future__ import annotations

import html
import json
import math
import re
from datetime import datetime, timezone
from typing import Any, Callable

BANNER = ("Label: SIMULATED. Every number below comes from the server physics run (RK4) and Build/fitter. "
          "Nothing here is MEASURED from a real video.")
IMAGE_MODEL, IMAGE_USD = "muse-image-1.0", 0.01  # flat per generated image (dev.meta.ai/docs/image-generation, Nov 1)
IMAGE_NOTE = "Illustration generated by muse-image-1.0; decorative only, not data."


def illustrate(title: str, send: Callable[[str, bytes, str, float], Any] | None = None, ledger: Any = None) -> str | None:
    """Optional report illustration via the images endpoint, cost reserved/settled in daily_cap. Never raises."""
    from Build.agent.core import _send
    from Build.guardrails import daily_cap
    send, ledger = send or _send, ledger or daily_cap
    try:
        rid = ledger.reserve("Meta Model API", IMAGE_USD, "N12 lab report illustration")
    except Exception:
        return None  # cap reached or ledger unavailable: the report ships without a picture
    prompt = ("Clean textbook-style illustration of a school physics lab experiment: " + title.split(": ", 1)[-1]
              + ". Simple apparatus on a bench, white background, no numbers, no text, no labels.")
    try:
        body = send("/images/generations", json.dumps({"model": IMAGE_MODEL, "prompt": prompt, "n": 1}).encode(),
                    "application/json", 120)
        b64 = body["data"][0]["b64_json"]
        ledger.settle(rid, IMAGE_USD)
        return b64 if isinstance(b64, str) and re.fullmatch(r"[A-Za-z0-9+/]+={0,2}", b64) else None
    except Exception:
        ledger.settle(rid, 0)  # failed or filtered images are not billed
        return None


def _f(x: Any, d: int = 4) -> str:
    return "n/a" if x is None else f"{x:.{d}g}"


def _pm(q: dict[str, Any] | None) -> str:
    if not q:
        return "n/a"
    s = q.get("uncertainty")
    return f"{_f(q['value'], 6)} ± {_f(s, 2)} {q['unit']}" if s is not None else f"{_f(q['value'], 6)} {q['unit']} (uncertainty unavailable)"


def _conclude(r: dict[str, Any], g_in: float) -> str:
    if r.get("status") != "ok":
        return f"{r['object_id']}: no result ({r.get('error')})."
    if "g" in r:
        g, s = r["g"]["value"], r["g"]["uncertainty"]
        z = abs(g - g_in) / s if s else math.inf
        return (f"{r['object_id']}: g = {_pm(r['g'])} (SIMULATED) against the scene setting {_f(g_in, 6)} m/s^2; "
                f"difference {_f(g - g_in, 3)} m/s^2 ({_f(z, 2)} sigma), "
                + ("consistent." if z <= 2 else "not consistent within 2 sigma."))
    ref = r.get("large_angle_period_s") or r.get("undamped_period_s")
    tail = f"; THEORY reference {_f(ref['value'], 6)} s" if ref else ""
    return f"{r['object_id']}: period T = {_pm(r['period'])} (SIMULATED){tail}."


def render(scene: dict[str, Any], engine: str, results: list[dict[str, Any]], now: datetime | None = None,
           image_b64: str | None = None) -> dict[str, str]:
    now = now or datetime.now(timezone.utc)
    g_in = math.hypot(*scene["gravity"])
    kinds = {r["kind"] for r in results}
    aims = (["measure the gravitational acceleration g from a falling object"] if kinds & {"ball", "block"} else []) + \
           (["find the period of a pendulum"] if "pendulum" in kinds else []) + \
           (["find the period of a mass on a spring"] if "spring" in kinds else [])
    title = "Lab report: " + ("; ".join(aims) or "virtual lab run")
    md = [f"# {title}", "", f"_{BANNER}_", "", f"Generated {now:%Y-%m-%d %H:%M} UTC.", "",
          "## Aim", "", f"Use the virtual lab to {' and '.join(aims) or 'run the scene'}.", "",
          "## Setup", "", f"- Gravity setting: {_f(g_in, 6)} m/s^2 (scene input); floor: {scene['room'].get('kind')}",
          f"- Engine: {engine}", "", "| id | kind | mass (kg) | size (m) | position (m) | params |", "|---|---|---|---|---|---|"]
    for o in scene["objects"]:
        params = ", ".join(f"{k} {_f(v)}" for k, v in o["params"].items()) or "none"
        md.append(f"| {o['id']} | {o['kind']} | {_f(o['mass'])} | {' x '.join(_f(s) for s in o['size'])} | "
                  f"{', '.join(_f(p) for p in o['position'])} | {params} |")
    md += ["", "## Data", "", "| object | samples | duration (s) | ended |", "|---|---|---|---|"]
    for r in results:
        md.append(f"| {r['object_id']} | {r['samples']} | {_f(r['duration_s'])} | {r.get('ended', 'duration')} |")
    md += ["", "## Fit with uncertainty", "", "Uncertainties are one sigma, from Build/fitter with the declared noise below.", ""]
    for r in results:
        if r.get("status") != "ok":
            md.append(f"- {r['object_id']}: {r.get('error')}")
        elif "g" in r:
            md.append(f"- {r['object_id']}: g = {_pm(r['g'])} by {r['g']['method']}; fall {_f(r['drop_height_m'])} m; "
                      f"rmse {_f(r['rmse_m'], 2)} m; declared position sigma {_f(r['declared_position_sigma_m'])} m (assumed)")
        else:
            md.append(f"- {r['object_id']}: T = {_pm(r['period'])} by {r['period']['method']} over {r['crossings']} "
                      f"crossings; declared crossing sigma {_f(r['declared_crossing_sigma_s'], 3)} s (assumed)")
            for k in ("small_angle_period_s", "large_angle_period_s", "undamped_period_s"):
                if k in r:
                    md.append(f"  - THEORY {k.replace('_s', '').replace('_', ' ')}: {_f(r[k]['value'], 6)} s")
    conclusion = " ".join(_conclude(r, g_in) for r in results) or "No sensor objects produced data."
    md += ["", "## Conclusion", "", conclusion, "",
           "Limits: an ideal simulation recovers its own inputs; this checks the method, not the real world. "
           "Scale and noise are declared, not calibrated.", ""]
    if image_b64:
        md += ["## Illustration", "", f"![Illustration](report.webp) {IMAGE_NOTE}", ""]
    markdown = "\n".join(md)
    page = to_html(markdown, title)
    if image_b64:  # base64 alphabet only, so it is safe inside the attribute
        page = page.replace("</body>", f'<figure><img alt="{IMAGE_NOTE}" style="max-width:100%" '
                                       f'src="data:image/webp;base64,{image_b64}"><figcaption>{IMAGE_NOTE}</figcaption></figure></body>')
    return {"title": title, "markdown": markdown, "html": page, "conclusion": conclusion}


def to_html(markdown: str, title: str) -> str:
    out, rows = [], []
    flush = lambda: (out.append("<table>" + "".join(rows) + "</table>"), rows.clear()) if rows else None
    for line in markdown.splitlines():
        if line.startswith("!["):
            continue  # the HTML embeds the image itself
        if line.startswith("|"):
            if not set(line) <= set("|-"):
                cells = [html.escape(c.strip()) for c in line.strip("|").split("|")]
                tag = "th" if not rows else "td"
                rows.append("<tr>" + "".join(f"<{tag}>{c}</{tag}>" for c in cells) + "</tr>")
            continue
        flush()
        e = html.escape(line.strip())
        if line.startswith("## "):
            out.append(f"<h2>{e[3:]}</h2>")
        elif line.startswith("# "):
            out.append(f"<h1>{e[2:]}</h1>")
        elif line.lstrip().startswith("- "):
            out.append(f"<li>{e[2:]}</li>")
        elif e:
            out.append(f"<p>{e.strip('_')}</p>")
    flush()
    return (f"<!doctype html><html lang=\"en\"><meta charset=\"utf-8\"><title>{html.escape(title)}</title>"
            f"<body>{''.join(out)}</body></html>")
